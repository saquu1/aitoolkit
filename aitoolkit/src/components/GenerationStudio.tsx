interface GenerationConfig {
  target: 'prisma' | 'nextjs' | 'react' | 'nestjs' | 'express'
  includeValidation: boolean
  includeTests: boolean
  includeDocs: boolean
  formatCode: boolean
  tableNameCase: 'camel' | 'pascal' | 'snake'
  columnNameCase: 'camel' | 'snake'
}

