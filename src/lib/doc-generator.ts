/**
 * Map SQL data type to JSON Schema type
 */
function mapToJSONType(dataType: string): string {
  const type = dataType.toUpperCase();

  if (['INT', 'BIGINT', 'SMALLINT', 'TINYINT'].includes(type)) {
    return 'integer';
  }

  if (['DECIMAL', 'NUMERIC', 'FLOAT', 'REAL', 'MONEY', 'SMALLMONEY'].includes(type)) {
    return 'number';
  }

  if (['BIT'].includes(type)) {
    return 'boolean';
  }

  if (['DATETIME', 'DATETIME2', 'DATE', 'SMALLDATETIME', 'DATETIMEOFFSET'].includes(type)) {
    return 'string';
  }

  return 'string';
}

/**
 * Convert to PascalCase singular
 */
function toPascalSingular(name: string): string {
  let singular = name;

  if (singular.endsWith('ies')) {
    singular = singular.slice(0, -3) + 'y';
  } else if (singular.endsWith('ses') || singular.endsWith('xes')) {
    singular = singular.slice(0, -2);
  } else if (
    singular.endsWith('s') &&
    !singular.endsWith('ss') &&
    !singular.endsWith('us')
  ) {
    singular = singular.slice(0, -1);
  }

  return singular.charAt(0).toUpperCase() + singular.slice(1);
}

/**
 * Convert to kebab-case
 */
function toKebabCase(name: string): string {
  return name
    .replace(/([a-z])([A-Z])/g, '$1-$2')
    .replace(/[\s_]+/g, '-')
    .toLowerCase();
}
